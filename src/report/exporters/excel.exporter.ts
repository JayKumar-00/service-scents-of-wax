import {
  ReportColumn,
  ReportSummaryCard,
} from '../interfaces/report.interface';

export class ExcelExporter {
  public static export(params: {
    title: string;
    columns: ReportColumn[];
    records: any[];
    summary: Record<string, ReportSummaryCard>;
    filters: Record<string, any>;
    generatedBy: string;
  }): string {
    const { title, columns, records, summary, filters, generatedBy } = params;
    const nowStr = new Date().toISOString();

    // 1. Generate XML Styles & Workbook Header
    let xml = `<?xml version="1.0"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:o="urn:schemas-microsoft-com:office:office"
 xmlns:x="urn:schemas-microsoft-com:office:excel"
 xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet"
 xmlns:html="http://www.w3.org/TR/REC-html40">
 <DocumentProperties xmlns="urn:schemas-microsoft-com:office:office">
  <Author>${this.escape(generatedBy)}</Author>
  <Created>${nowStr}</Created>
  <Company>Scents Of Wax</Company>
 </DocumentProperties>
 <Styles>
  <Style ss:ID="Default" ss:Name="Normal">
   <Alignment ss:Vertical="Center"/>
   <Borders/>
   <Font ss:FontName="Segoe UI" x:CharSet="1" x:Family="Swiss" ss:Size="11" ss:Color="#0F172A"/>
   <Interior/>
   <NumberFormat/>
   <Protection/>
  </Style>
  <Style ss:ID="Title">
   <Font ss:FontName="Segoe UI" ss:Size="16" ss:Bold="1" ss:Color="#0F172A"/>
   <Alignment ss:Vertical="Center"/>
  </Style>
  <Style ss:ID="Bold">
   <Font ss:FontName="Segoe UI" ss:Size="11" ss:Bold="1" ss:Color="#1E293B"/>
   <Alignment ss:Vertical="Center"/>
  </Style>
  <Style ss:ID="Header">
   <Font ss:FontName="Segoe UI" ss:Size="11" ss:Bold="1" ss:Color="#FFFFFF"/>
   <Interior ss:Color="#0F172A" ss:Pattern="Solid"/>
   <Alignment ss:Horizontal="Center" ss:Vertical="Center"/>
   <Borders>
    <Border ss:Position="Bottom" ss:LineStyle="Continuous" ss:Weight="1" ss:Color="#FFFFFF"/>
   </Borders>
  </Style>
  <Style ss:ID="Currency">
   <NumberFormat ss:Format="&quot;₹&quot;#,##0.00;[Red]-&quot;₹&quot;#,##0.00;&quot;₹&quot;0.00"/>
  </Style>
  <Style ss:ID="Number">
   <NumberFormat ss:Format="#,##0"/>
  </Style>
  <Style ss:ID="Date">
   <NumberFormat ss:Format="YYYY-MM-DD HH:MM:SS"/>
  </Style>
  <Style ss:ID="StatusSuccess">
   <Interior ss:Color="#DCFCE7" ss:Pattern="Solid"/>
   <Font ss:FontName="Segoe UI" ss:Size="10" ss:Bold="1" ss:Color="#15803D"/>
   <Alignment ss:Horizontal="Center" ss:Vertical="Center"/>
  </Style>
  <Style ss:ID="StatusWarning">
   <Interior ss:Color="#FEF9C3" ss:Pattern="Solid"/>
   <Font ss:FontName="Segoe UI" ss:Size="10" ss:Bold="1" ss:Color="#A16207"/>
   <Alignment ss:Horizontal="Center" ss:Vertical="Center"/>
  </Style>
  <Style ss:ID="StatusDanger">
   <Interior ss:Color="#FEE2E2" ss:Pattern="Solid"/>
   <Font ss:FontName="Segoe UI" ss:Size="10" ss:Bold="1" ss:Color="#B91C1C"/>
   <Alignment ss:Horizontal="Center" ss:Vertical="Center"/>
  </Style>
 </Styles>
    `;

    // 2. Generate Sheet 1: Summary Page
    xml += `
 <Worksheet ss:Name="Summary">
  <Table ss:ExpandedColumnCount="5" ss:ExpandedRowCount="100" x:FullColumns="1" x:FullRows="1" ss:DefaultRowHeight="20">
   <Column ss:AutoFitWidth="0" ss:Width="200"/>
   <Column ss:AutoFitWidth="0" ss:Width="200"/>
   <Column ss:AutoFitWidth="0" ss:Width="300"/>
   
   <Row ss:Height="30">
    <Cell ss:StyleID="Title"><Data ss:Type="String">${this.escape(title)} - Summary</Data></Cell>
   </Row>
   <Row>
    <Cell ss:StyleID="Bold"><Data ss:Type="String">Generated By:</Data></Cell>
    <Cell><Data ss:Type="String">${this.escape(generatedBy)}</Data></Cell>
   </Row>
   <Row>
    <Cell ss:StyleID="Bold"><Data ss:Type="String">Generated On:</Data></Cell>
    <Cell><Data ss:Type="String">${new Date().toLocaleString('en-IN')}</Data></Cell>
   </Row>
   
   <Row><Cell><Data ss:Type="String"/></Cell></Row>
   
   <Row ss:Height="25">
    <Cell ss:StyleID="Header"><Data ss:Type="String">KPI Metric</Data></Cell>
    <Cell ss:StyleID="Header"><Data ss:Type="String">Value</Data></Cell>
    <Cell ss:StyleID="Header"><Data ss:Type="String">Description</Data></Cell>
   </Row>
    `;

    // Add KPI cards data
    for (const kpi of Object.values(summary)) {
      const isNum =
        typeof kpi.value === 'number' || !isNaN(parseFloat(String(kpi.value)));
      const valueType = isNum ? 'Number' : 'String';
      const cleanVal = isNum ? parseFloat(String(kpi.value)) : kpi.value;
      const cellStyle =
        kpi.type === 'currency'
          ? ' ss:StyleID="Currency"'
          : kpi.type === 'number'
            ? ' ss:StyleID="Number"'
            : '';

      xml += `
   <Row ss:Height="20">
    <Cell ss:StyleID="Bold"><Data ss:Type="String">${this.escape(kpi.label)}</Data></Cell>
    <Cell${cellStyle}><Data ss:Type="${valueType}">${isNum ? cleanVal : this.escape(cleanVal)}</Data></Cell>
    <Cell><Data ss:Type="String">${this.escape(kpi.description ?? '')}</Data></Cell>
   </Row>
      `;
    }

    xml += `
   <Row><Cell><Data ss:Type="String"/></Cell></Row>
   <Row><Cell ss:StyleID="Bold"><Data ss:Type="String">Filters Applied</Data></Cell></Row>
    `;

    const filterEntries = Object.entries(filters).filter(
      ([_, v]) => v !== undefined && v !== null && v !== '',
    );
    if (filterEntries.length === 0) {
      xml += `
   <Row>
    <Cell><Data ss:Type="String">None</Data></Cell>
   </Row>
      `;
    } else {
      for (const [k, v] of filterEntries) {
        const displayKey = k
          .replace(/([A-Z])/g, ' $1')
          .replace(/^./, (str) => str.toUpperCase());
        xml += `
   <Row>
    <Cell ss:StyleID="Bold"><Data ss:Type="String">${this.escape(displayKey)}</Data></Cell>
    <Cell><Data ss:Type="String">${this.escape(v)}</Data></Cell>
   </Row>
        `;
      }
    }

    xml += `
  </Table>
 </Worksheet>
    `;

    // 3. Generate Sheet 2: Data Page
    xml += `
 <Worksheet ss:Name="Data">
  <Table ss:ExpandedColumnCount="${columns.length + 1}" ss:ExpandedRowCount="${records.length + 10}" x:FullColumns="1" x:FullRows="1" ss:DefaultRowHeight="20">
    `;

    // Column widths
    for (const col of columns) {
      const width =
        col.type === 'date' ? 180 : col.type === 'currency' ? 120 : 140;
      xml += `   <Column ss:AutoFitWidth="0" ss:Width="${width}"/>\n`;
    }

    // Header row
    xml += `   <Row ss:Height="25">\n`;
    for (const col of columns) {
      xml += `    <Cell ss:StyleID="Header"><Data ss:Type="String">${this.escape(col.label)}</Data></Cell>\n`;
    }
    xml += `   </Row>\n`;

    // Data rows
    for (const rec of records) {
      xml += `   <Row>\n`;
      for (const col of columns) {
        const val = rec[col.name];

        if (val === null || val === undefined) {
          xml += `    <Cell><Data ss:Type="String"></Data></Cell>\n`;
          continue;
        }

        if (col.type === 'currency') {
          const num = typeof val === 'number' ? val : parseFloat(String(val));
          xml += `    <Cell ss:StyleID="Currency"><Data ss:Type="Number">${isNaN(num) ? 0 : num}</Data></Cell>\n`;
        } else if (col.type === 'number') {
          const num = typeof val === 'number' ? val : parseInt(String(val), 10);
          xml += `    <Cell ss:StyleID="Number"><Data ss:Type="Number">${isNaN(num) ? 0 : num}</Data></Cell>\n`;
        } else if (col.type === 'date') {
          // Format ISO date without milliseconds/timezone for SpreadsheetML datetime type
          const date = new Date(val);
          const iso = date.toISOString().split('.')[0]; // YYYY-MM-DDTHH:MM:SS
          xml += `    <Cell ss:StyleID="Date"><Data ss:Type="DateTime">${iso}</Data></Cell>\n`;
        } else if (col.type === 'status') {
          const statusStr = String(val).toUpperCase();
          let style = 'ss:StyleID="Default"';
          if (
            [
              'DELIVERED',
              'COMPLETED',
              'ACTIVE',
              'PAID',
              'APPROVED',
              'SUCCESS',
              'IN_STOCK',
            ].includes(statusStr)
          ) {
            style = 'ss:StyleID="StatusSuccess"';
          } else if (
            [
              'PENDING',
              'PROCESSING',
              'SCHEDULED',
              'UNPAID',
              'LOW_STOCK',
              'IN_TRANSIT',
              'OUT_FOR_DELIVERY',
            ].includes(statusStr)
          ) {
            style = 'ss:StyleID="StatusWarning"';
          } else if (
            [
              'CANCELLED',
              'FAILED',
              'OUT_OF_STOCK',
              'REJECTED',
              'BLOCKED',
              'FROZEN',
            ].includes(statusStr)
          ) {
            style = 'ss:StyleID="StatusDanger"';
          }
          xml += `    <Cell ${style}><Data ss:Type="String">${this.escape(val)}</Data></Cell>\n`;
        } else {
          xml += `    <Cell><Data ss:Type="String">${this.escape(val)}</Data></Cell>\n`;
        }
      }
      xml += `   </Row>\n`;
    }

    // Totals row (only if there are records and at least one currency or number column)
    if (records.length > 0) {
      xml += `   <Row ss:Height="22">\n`;
      let totalIndex = 0;
      for (const col of columns) {
        if (totalIndex === 0) {
          xml += `    <Cell ss:StyleID="Bold"><Data ss:Type="String">Total</Data></Cell>\n`;
        } else if (col.type === 'currency') {
          // R2C: starting from row index 2 (R2), C is current column. R[-1]C is the cell directly above this totals row.
          xml += `    <Cell ss:Formula="=SUM(R2C:R[-1]C)" ss:StyleID="Currency"><Data ss:Type="Number">0</Data></Cell>\n`;
        } else if (col.type === 'number') {
          xml += `    <Cell ss:Formula="=SUM(R2C:R[-1]C)" ss:StyleID="Number"><Data ss:Type="Number">0</Data></Cell>\n`;
        } else {
          xml += `    <Cell><Data ss:Type="String"></Data></Cell>\n`;
        }
        totalIndex++;
      }
      xml += `   </Row>\n`;
    }

    xml += `
  </Table>
  <WorksheetOptions xmlns="urn:schemas-microsoft-com:office:excel">
   <Views>
    <View>
     <ActiveTable>0</ActiveTable>
     <FreezePanes/>
     <FrozenNoSplit/>
     <SplitHorizontal>1</SplitHorizontal>
     <TopRowBottomPane>1</TopRowBottomPane>
     <ActivePane>2</ActivePane>
    </View>
   </Views>
  </WorksheetOptions>
 </Worksheet>
</Workbook>
    `;

    return xml;
  }

  private static escape(value: any): string {
    if (value == null) return '';
    return String(value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }
}
